// Email previews (P0.8-02): every email kind in the catalog, rendered by the real template with the catalog's invented
// data, as the HTML and the plain text a recipient gets. scripts/render-emails.ts writes them to docs/email-previews/
// so they can be read in a browser; tests/email-previews.test.ts fails when a file is missing or out of date. Pure: no
// database, no network, no clock.
import { categoryOf, isStaffCategory, SYSTEM_WHY, type SystemCategory } from "../notify-categories.ts";
import { catalog } from "./catalog.ts";
import { renderEmail } from "./template.ts";

export type Preview = { kind: string; subject: string; html: string; text: string };

export function previews(): Preview[] {
  return catalog().map((c) => {
    const cat = categoryOf(c.category);
    const { html, text } = renderEmail(c.content, {
      appUrl: "https://kabsi.co",
      defaultWhy: cat?.why ?? SYSTEM_WHY[c.category as SystemCategory] ?? "You asked for this email.",
      unsubscribePage: cat?.switchable ? "https://kabsi.co/unsubscribe?t=SAMPLE" : null,
      staff: isStaffCategory(c.category), example: true,
    });
    return { kind: c.kind, subject: c.content.subject, html, text: `Subject: ${c.content.subject}\n\n${text}\n` };
  });
}

/** The index page: one link per email kind, with its subject. */
export function previewIndex(list: Preview[]): string {
  const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  const rows = list.map((p) => `<li><a href="${p.kind}.html">${esc(p.kind)}</a>: ${esc(p.subject)} (<a href="${p.kind}.txt">text</a>)</li>`).join("\n");
  return `<!doctype html>\n<meta charset="utf-8">\n<title>Kabsi email previews</title>\n<h1>Kabsi email previews (${list.length})</h1>\n<p>Generated by scripts/render-emails.ts from the email catalog with invented data. Do not edit by hand.</p>\n<ul>\n${rows}\n</ul>\n`;
}
